// ---------------------------------------------------------------------------
// Word-search generation (الكلمات الضائعة)
// ---------------------------------------------------------------------------

class WordSearchPuzzle {
  const WordSearchPuzzle({
    required this.size,
    required this.grid,
    required this.words,
    required this.placements,
  });
  final int size;

  /// grid[row][col] single-letter cells.
  final List<List<String>> grid;

  /// Words actually hidden in the grid.
  final List<String> words;

  /// word -> flat cell indices (row * size + col) in reading order.
  final Map<String, List<int>> placements;
}

/// Builds a word-search puzzle: hides up to [wordCount] bank words
/// (3-6 letters) horizontally or vertically in a [size]×[size] grid,
/// then fills the remaining cells with random letters.
WordSearchPuzzle generateWordSearch({
  required int size,
  required int wordCount,
  required Random rand,
}) {
  final grid = List.generate(size, (_) => List<String>.filled(size, ''));
  final maxLen = min(6, size);
  final candidates = wordBank.where((w) {
    final l = w.runes.length;
    return l >= 3 && l <= maxLen;
  }).toList()
    ..shuffle(rand);
  final placed = <String>[];
  final placements = <String, List<int>>{};
  for (final word in candidates) {
    if (placed.length >= wordCount) break;
    final letters = lettersOf(word);
    var done = false;
    for (var attempt = 0; attempt < 80 && !done; attempt++) {
      final horizontal = rand.nextBool();
      final dr = horizontal ? 0 : 1;
      final dc = horizontal ? 1 : 0;
      final maxR = size - 1 - dr * (letters.length - 1);
      final maxC = size - 1 - dc * (letters.length - 1);
      if (maxR < 0 || maxC < 0) continue;
      final r0 = rand.nextInt(maxR + 1);
      final c0 = rand.nextInt(maxC + 1);
      var ok = true;
      for (var i = 0; i < letters.length; i++) {
        final cell = grid[r0 + dr * i][c0 + dc * i];
        if (cell.isNotEmpty && cell != letters[i]) {
          ok = false;
          break;
        }
      }
      if (!ok) continue;
      final idxs = <int>[];
      for (var i = 0; i < letters.length; i++) {
        grid[r0 + dr * i][c0 + dc * i] = letters[i];
        idxs.add((r0 + dr * i) * size + (c0 + dc * i));
      }
      placed.add(word);
      placements[word] = idxs;
      done = true;
    }
  }
  for (var r = 0; r < size; r++) {
    for (var c = 0; c < size; c++) {
      if (grid[r][c].isEmpty) grid[r][c] = randomLetter(rand);
    }
  }
  return WordSearchPuzzle(
    size: size,
    grid: grid,
    words: placed,
    placements: placements,
  );
}

// ---------------------------------------------------------------------------
// Boggle-style grid generation (لوحة الكلمات)
// ---------------------------------------------------------------------------

class BoggleGrid {
  const BoggleGrid({required this.cells, required this.placedWords});

  /// 16 single-letter cells, row-major.
  final List<String> cells;

  /// Words guaranteed findable in the grid (placed along adjacent paths).
  final List<String> placedWords;
}

/// Builds a 4×4 letter board containing [wordTarget] bank words laid out
/// along random adjacent (8-direction) paths, filled with random letters.
BoggleGrid generateBoggleGrid({required Random rand, int wordTarget = 5}) {
  const size = 4;
  final cells = List<String>.filled(size * size, '');
  final candidates = wordBank.where((w) {
    final l = w.runes.length;
    return l >= 3 && l <= 5;
  }).toList()
    ..shuffle(rand);
  final placed = <String>[];
  for (final word in candidates) {
    if (placed.length >= wordTarget) break;
    final letters = lettersOf(word);
    var done = false;
    for (var attempt = 0; attempt < 40 && !done; attempt++) {
      final path = <int>[];
      var cur = rand.nextInt(size * size);
      if (cells[cur].isNotEmpty && cells[cur] != letters[0]) continue;
      path.add(cur);
      var ok = true;
      for (var i = 1; i < letters.length; i++) {
        final r = cur ~/ size;
        final c = cur % size;
        final neighbors = <int>[];
        for (var dr = -1; dr <= 1; dr++) {
          for (var dc = -1; dc <= 1; dc++) {
            if (dr == 0 && dc == 0) continue;
            final nr = r + dr;
            final nc = c + dc;
            if (nr < 0 || nr >= size || nc < 0 || nc >= size) continue;
            final idx = nr * size + nc;
            if (path.contains(idx)) continue;
            if (cells[idx].isNotEmpty && cells[idx] != letters[i]) continue;
            neighbors.add(idx);
          }
        }
        if (neighbors.isEmpty) {
          ok = false;
          break;
        }
        cur = neighbors[rand.nextInt(neighbors.length)];
        path.add(cur);
      }
      if (!ok) continue;
      for (var i = 0; i < letters.length; i++) {
        cells[path[i]] = letters[i];
      }
      placed.add(word);
      done = true;
    }
  }
  for (var i = 0; i < cells.length; i++) {
    if (cells[i].isEmpty) cells[i] = randomLetter(rand);
  }
  return BoggleGrid(cells: cells, placedWords: placed);
}
