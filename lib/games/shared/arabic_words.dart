/// Flat, de-duplicated list of every bank word.
final List<String> wordBank =
    wordBankByCategory.values.expand((words) => words).toSet().toList();

/// Fast membership test for the word bank.
final Set<String> wordBankSet = wordBank.toSet();

/// Splits a word into single-codepoint letter strings (Arabic is in the
/// BMP, but going through runes keeps this correct in general).
List<String> lettersOf(String word) =>
    word.runes.map(String.fromCharCode).toList();

/// True when [word] can be assembled from the multiset [letters].
bool canBuildFrom(String word, List<String> letters) {
  final pool = <String, int>{};
  for (final l in letters) {
    pool[l] = (pool[l] ?? 0) + 1;
  }
  for (final ch in lettersOf(word)) {
    final n = pool[ch] ?? 0;
    if (n == 0) return false;
    pool[ch] = n - 1;
  }
  return true;
}

/// Every bank word that can be assembled from [letters].
List<String> possibleWords(List<String> letters) =>
    wordBank.where((w) => canBuildFrom(w, letters)).toList();

/// Points for a found word, by its letter count.
int wordScore(int length) => switch (length) {
  3 => 10,
  4 => 20,
  5 => 35,
  6 => 55,
  7 => 80,
  _ => length * 10,
};

/// Frequency-flavoured pool of Arabic letters for filling grids.
const String _letterPool =
    'اااااااالللللللمممممننننررررسسستتتبببععقققففددححججششخخككططصصههوييةةىذزغضظثأإآ';

String randomLetter(Random rand) {
  final letters = lettersOf(_letterPool);
  return letters[rand.nextInt(letters.length)];
}

